-- ============ ОЦЕНКИ (90 000: ~6 на студента) ============
INSERT INTO grades (student_id, course_id, grade, is_passed)
SELECT sid, cid, gr, gr >= 3
FROM (
    SELECT
        1 + (i % 15000) AS sid,
        1 + ((i * 7) % 200) AS cid,
        2 + ((i * 13) % 4) AS gr   -- оценки 2, 3, 4, 5
    FROM generate_series(1, 90000) i
) t;

