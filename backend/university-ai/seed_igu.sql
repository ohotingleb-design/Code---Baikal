-- ============ СТУДЕНТЫ (15 000) ============
INSERT INTO students (student_id_number, group_name, faculty_id, enrollment_year)
SELECT
    'ST-' || LPAD(i::text, 6, '0'),
    LPAD((enr % 100)::text, 2, '0') || (ARRAY['И','Ф','И','П','Ю','Г','Б','Ф','Х','Г'])[fac] || (1 + (i % 3))::text,
    fac,
    enr
FROM (
    SELECT i,
        1 + (i % 10) AS fac,
        2020 + (i % 6) AS enr
    FROM generate_series(1, 15000) i
) t;

